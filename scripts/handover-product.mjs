#!/usr/bin/env node
// Write the product records of an archetype from its work system (see handover.md).
// Usage: node scripts/handover-product.mjs <work system> <archetype repository>
// Run it after the workspace and projects/ are in the archetype: it rewrites the test tags there too.
import fs from "node:fs";
import path from "node:path";

const [work, archetype] = process.argv.slice(2).map((dir) => path.resolve(dir ?? ""));
if (!fs.existsSync(path.join(work, ".product", "system.md"))) throw new Error(`No work system at ${work}`);
if (!fs.existsSync(path.join(archetype, "projects"))) throw new Error(`Copy the workspace to ${archetype} first`);

const source = path.join(work, ".product");
const target = path.join(archetype, ".product");
const foundation = fs
  .readdirSync(path.join(source, "foundation"))
  .filter((name) => name.endsWith(".spec.md"))
  .map((name) => name.slice(0, -".spec.md".length));

/** The frontmatter fields of a spec, with no trailing comment. */
function frontmatter(text) {
  const block = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text)?.[1] ?? "";
  return Object.fromEntries(
    block.split(/\r?\n/).map((line) => {
      const [key, ...rest] = line.split(":");
      return [key.trim(), rest.join(":").replace(/\s+#.*$/, "").trim()];
    }),
  );
}

// 1. Copy system.md, the model and only the foundation specs (never the fix and refactor specs that repaired debt).
fs.rmSync(target, { recursive: true, force: true });
fs.mkdirSync(target, { recursive: true });
fs.copyFileSync(path.join(source, "system.md"), path.join(target, "system.md"));
fs.cpSync(path.join(source, "model"), path.join(target, "model"), { recursive: true });
const specsSource = path.join(source, "specs");
const specs = fs
  .readdirSync(specsSource, { recursive: true })
  .filter((name) => /S\d{4}-[^\\/]+\.md$/.test(name))
  .map((name) => {
    const text = fs.readFileSync(path.join(specsSource, name), "utf8");
    return { name: path.basename(name), text, fields: frontmatter(text) };
  })
  .filter(({ fields }) => foundation.includes(fields.slug))
  .sort((a, b) => a.fields.id.localeCompare(b.fields.id));
for (const spec of specs) {
  const folder = path.join(target, "specs", spec.fields.type);
  fs.mkdirSync(folder, { recursive: true });
  const clean = spec.text.replace(/^(type:\s*\w+)\s+#.*$/m, "$1");
  fs.writeFileSync(path.join(folder, spec.name), clean);
}

// 2. Number the specs in delivery order with no gaps, and rewrite each reference in the archetype.
const map = new Map(specs.map(({ fields }, index) => [fields.id, `S${String(index + 1).padStart(4, "0")}`]));
const skip = new Set(["node_modules", ".git", "coverage"]);
function textFiles(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    if (skip.has(entry.name)) return [];
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return textFiles(full);
    return /\.(md|ts|tsx|json)$/.test(entry.name) && entry.name !== "package-lock.json" ? [full] : [];
  });
}
for (const file of textFiles(archetype)) {
  const text = fs.readFileSync(file, "utf8");
  const next = text.replace(/\bS\d{4}(?=\b|-)/g, (id) => map.get(id) ?? id);
  if (next !== text) fs.writeFileSync(file, next);
}
for (const { name, fields } of specs) {
  const folder = path.join(target, "specs", fields.type);
  fs.renameSync(path.join(folder, name), path.join(folder, name.replace(fields.id, map.get(fields.id))));
}

// 3. Write PRD.md: the shipped features by domain, as `aidd release` writes it.
const features = specs.filter(({ fields }) => fields.type === "feat");
const domains = [...new Set(features.map(({ fields }) => fields.domain))];
const lines = ["# PRD", "", "Shipped features by domain. Generated by `aidd release`; do not edit.", ""];
for (const domain of domains) {
  lines.push(`## ${domain}`, "");
  for (const { name, text, fields } of features.filter((spec) => spec.fields.domain === domain)) {
    const title = /^# \S+ — (.+)$/m.exec(text)?.[1] ?? fields.slug;
    const id = map.get(fields.id);
    lines.push(`- [${id}](specs/feat/${name.replace(fields.id, id)}) ${title}`);
  }
  lines.push("");
}
fs.writeFileSync(path.join(target, "PRD.md"), lines.join("\n"));
console.log([...map].map(([from, to]) => `${from}→${to}`).join(" "));
